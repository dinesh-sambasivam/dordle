export function getDailyWordIndex(date?: Date): number {
  const d = date || new Date();
  const start = new Date(DORDLE_START_DATE);
  const startUTC = Date.UTC(start.getFullYear(), start.getMonth(), start.getDate());
  const todayUTC = Date.UTC(d.getFullYear(), d.getMonth(), d.getDate());
  const diff = Math.floor((todayUTC - startUTC) / (1000 * 60 * 60 * 24));
  return Math.max(0, diff) % DAILY_WORDS.length;
}

export function getDailyWord(date?: Date): string {
  return DAILY_WORDS[getDailyWordIndex(date)];
}

export function getDailyNumber(date?: Date): number {
  return getDailyWordIndex(date) + 1;
}

export function getTodayDateLabel(date?: Date): string {
  const d = date || new Date();
  return d.toLocaleDateString('en-US', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' });
}
